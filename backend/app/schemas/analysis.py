"""
Analysis Catalogue & Execution Schemas
Directly maps to Section 5.3, 5.4, 6.1, 8.1 and 8.2 of the project specification.
"""

import uuid
from enum import Enum
from typing import List, Dict, Any, Optional
from pydantic import Field
from app.schemas.common import BaseSchema


class AnalysisOperationEnum(str, Enum):
    DESCRIPTIVE_STATS = "descriptive_stats"
    HISTOGRAM = "histogram"
    BOXPLOT = "boxplot"
    VIOLIN_PLOT = "violin_plot"
    CORRELATION = "correlation"
    GROUP_BY = "group_by"
    OUTLIER_IQR = "outlier_iqr"
    OUTLIER_ZSCORE = "outlier_zscore"
    CROSSTAB = "crosstab"
    TIME_TREND = "time_trend"
    SCATTER_PLOT = "scatter_plot"
    CUSTOM_CHART = "custom_chart"


class MissingPolicyEnum(str, Enum):
    EXCLUDE_AND_REPORT = "exclude_and_report"
    EXCLUDE_SILENT = "exclude_silent"
    FAIL_ON_MISSING = "fail_on_missing"


class ScopeEnum(str, Enum):
    FULL_DATASET = "full_dataset"
    SAMPLE = "sample"


class StructuredAnalysisPlan(BaseSchema):
    """Machine-validated structured plan generated by AI or user interface."""
    operation: AnalysisOperationEnum
    column: Optional[str] = None
    target_columns: Optional[List[str]] = None
    filter_expression: Optional[str] = None
    group_by_column: Optional[str] = None
    aggregation: Optional[str] = "mean"
    bins: Optional[str] = "auto"
    missing_policy: MissingPolicyEnum = MissingPolicyEnum.EXCLUDE_AND_REPORT
    scope: ScopeEnum = ScopeEnum.FULL_DATASET
    chart_type: Optional[str] = None
    parameters: Dict[str, Any] = Field(default_factory=dict)


class AnalysisRequestCreate(BaseSchema):
    session_id: uuid.UUID
    user_query: str
    override_plan: Optional[StructuredAnalysisPlan] = None


class AnalysisRequestResponse(BaseSchema):
    id: uuid.UUID
    session_id: uuid.UUID
    user_query: str
    structured_plan: Optional[StructuredAnalysisPlan] = None
    status: str
    error_message: Optional[str] = None


class AnalysisResultResponse(BaseSchema):
    """Reusable result object containing chart, code, statistics, and guardrail warnings."""
    id: uuid.UUID
    request_id: uuid.UUID
    operation_type: str
    summary_text: str  # Plain-language explanation
    execution_code: str  # Reproducible Python/SQL snippet
    records_examined: int
    records_used: int
    is_sampled: bool
    sample_size: Optional[int] = None
    plot_spec: Optional[Dict[str, Any]] = None  # Plotly JSON schema
    data_table: Optional[List[Dict[str, Any]]] = None  # Result records
    warnings: List[str] = Field(default_factory=list)  # Data limitations, small group size warnings
    execution_time_ms: float
