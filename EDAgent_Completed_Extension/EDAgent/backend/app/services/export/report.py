def _f(v: Any, nd: int = 4) -> str:
    if v is None:
        return "–"
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, int):
        return f"{v:,}"
    if isinstance(v, float):
        return f"{v:,.{nd}g}" if abs(v) < 1e6 else f"{v:,.0f}"
    return str(v)


def _p(text: str) -> Block:
    return {"type": "p", "text": text}


def _h(text: str) -> Block:
    return {"type": "h3", "text": text}


def _ul(items: List[str]) -> Block:
    return {"type": "ul", "items": items}


def _table(columns: List[str], rows: List[List[Any]], caption: str = "") -> Block:
    return {"type": "table", "columns": columns, "rows": [[_f(c) if not isinstance(c, str) else c for c in r] for r in rows], "caption": caption}


def _img(png: bytes, caption: str) -> Block:
    return {"type": "image", "png": png, "caption": caption}


def _callout(kind: str, text: str) -> Block:
    return {"type": "callout", "kind": kind, "text": text}


def _code(text: str) -> Block:
    return {"type": "code", "text": text}


def _kv(pairs: List[tuple]) -> Block:
    return {"type": "kv", "pairs": [(k, _f(v) if not isinstance(v, str) else v) for k, v in pairs]}


def _png(spec: Dict[str, Any]) -> bytes:
    return render_bytes(spec, "png", dpi=130)


def _role_counts(cols: List[Dict[str, Any]]) -> Dict[str, int]:
    out: Dict[str, int] = {}
    for c in cols:
        out[c["semantic_role"]] = out.get(c["semantic_role"], 0) + 1
    return out


