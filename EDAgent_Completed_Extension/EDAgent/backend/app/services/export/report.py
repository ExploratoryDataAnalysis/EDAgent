"""
EDA report builder (HTML and PDF).

One content model feeds both outputs: `build_document` turns the stored dataset profile and the
session's stored analysis results into a list of sections made of simple blocks (paragraphs,
tables, images, callouts, code). `render_html` and `render_pdf` then draw those blocks. No
number is recomputed here: everything comes from the profiler output or from the structured
results the engine produced, so the report always matches what the backend calculated.

Trust labelling: text produced by the deterministic profiler/engine is marked "Computed", and
text written by a language model is marked "AI-written explanation" so a reader can always tell
them apart. All dataset-derived and user-derived strings are escaped on output.
"""

