COMPUTED = "Computed by the EDAgent profiler/engine (deterministic)."
AI_LABEL = "AI-written explanation: generated by a language model from the computed results. It is not part of the calculation; check it against the figures."


@dataclass
class ReportAnalysis:
    label: str                      # the user's question or the run label
    result: AnalysisResultResponse
    ai_text: Optional[str] = None   # only set when a language model wrote the explanation
    fallback_text: Optional[str] = None


@dataclass
class ReportInput:
    title: str
    concise: bool
    sections: List[str]
    dataset_id: str
    dataset_name: str
    original_filename: str
    file_format: str
    file_size_bytes: int
    checksum_sha256: str
    fingerprint: str
    parse_options: Dict[str, Any]
    profile: Dict[str, Any]
    analyses: List[ReportAnalysis]
    generated_at: datetime = field(default_factory=lambda: datetime.now(timezone.utc))


@dataclass
class Section:
    key: str
    number: int
    title: str
    blocks: List[Block] = field(default_factory=list)


