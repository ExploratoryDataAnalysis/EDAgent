def build_document(inp: ReportInput) -> List[Section]:
    """Sections in specification order; the numbering follows the spec even when some are skipped."""
    order = [s.value for s in S]
    chosen = set(inp.sections)
    out: List[Section] = []
    for n, key in enumerate(order, start=1):
        if key not in chosen:
            continue
        blocks = _cover(inp) if key == S.COVER.value else _BUILDERS[key](inp)
        out.append(Section(key=key, number=n, title=SECTION_TITLES[key], blocks=blocks))
    return out


