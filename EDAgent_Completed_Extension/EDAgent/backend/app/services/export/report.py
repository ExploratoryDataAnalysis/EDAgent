def _cover(inp: ReportInput) -> List[Block]:
    ov = inp.profile.get("overview", {})
    return [
        _kv([
            ("Dataset", inp.dataset_name),
            ("Original file", inp.original_filename),
            ("Format", inp.file_format.upper()),
            ("File size", f"{inp.file_size_bytes / 1024:,.1f} KB"),
            ("Rows × columns", f"{ov.get('total_rows', '?'):,} × {ov.get('total_columns', '?')}" if isinstance(ov.get("total_rows"), int) else "?"),
            ("Worksheet", inp.parse_options.get("sheet") or "–"),
            ("Dataset fingerprint", inp.fingerprint),
            ("Report generated", inp.generated_at.strftime("%Y-%m-%d %H:%M UTC")),
            ("Report mode", "Concise" if inp.concise else "Detailed"),
        ]),
        _callout("note", "How to read this report: statistics, tables and charts are computed by the EDAgent backend from your original file (which is never modified). "
                         "Text written by a language model is always labelled 'AI-written explanation'."),
    ]


def _executive_summary(inp: ReportInput) -> List[Block]:
    p = inp.profile
    cols = p.get("columns", [])
    ov = p.get("overview", {})
    roles = _role_counts(cols)
    miss = p.get("missingness", {})
    dup = p.get("duplicates", {})
    warns = p.get("quality_warnings", [])
    items = [
        f"The dataset has {ov.get('total_rows', 0):,} rows and {ov.get('total_columns', 0)} columns "
        f"({roles.get('measure', 0)} numeric measures, {roles.get('category', 0)} categorical, {roles.get('datetime', 0)} date/time, "
        f"{roles.get('identifier', 0)} identifier, {roles.get('boolean', 0)} boolean, {roles.get('text', 0)} text).",
        f"{miss.get('missing_cells', 0):,} of {miss.get('total_cells', 0):,} cells are missing ({_f(miss.get('overall_missing_percentage', 0))}%)"
        + (f"; most affected: {', '.join(sorted(miss.get('columns_with_missing', []), key=lambda c: -miss['per_column'].get(c, 0))[:3])}." if miss.get("columns_with_missing") else "."),
        f"{dup.get('exact_duplicate_rows_count', 0):,} exact duplicate rows ({_f(dup.get('exact_duplicate_percentage', 0))}%).",
    ]
    sev = {"high": 0, "medium": 0, "low": 0}
    for w in warns:
        sev[str(w.get("severity", "low")).lower()] = sev.get(str(w.get("severity", "low")).lower(), 0) + 1
    items.append(f"{len(warns)} data-quality finding(s): {sev['high']} high, {sev['medium']} medium, {sev['low']} low severity.")
    pairs = _correlation_pairs(p)
    if pairs:
        a, b, r = pairs[0]
        items.append(f"Strongest linear relationship between numeric columns: {a} and {b} (Pearson r = {r:.2f}). Correlation does not imply causation.")
    blocks: List[Block] = [_callout("computed", COMPUTED), _ul(items)]
    if inp.analyses:
        blocks += [_h(f"Analyses run in this session ({len(inp.analyses)})"), _ul([f"{a.label}: {a.result.summary_text}" for a in inp.analyses[: (5 if inp.concise else 12)]])]
        blocks.append(_p("Details, charts and any AI-written explanations are in sections 13 and 14."))
    return blocks


def _inventory(inp: ReportInput) -> List[Block]:
    ov = inp.profile.get("overview", {})
    cols = inp.profile.get("columns", [])
    rows = [[c["name"], c["storage_dtype"], c["inferred_type"], c["semantic_role"], c["non_null_count"], f"{c['missing_percentage']}%", c["distinct_count"]] for c in cols]
    return [
        _callout("computed", COMPUTED),
        _kv([("Rows", ov.get("total_rows")), ("Columns", ov.get("total_columns")), ("Estimated memory", f"{ov.get('memory_estimate_bytes', 0) / 1024:,.0f} KB")]),
        _table(["Column", "Stored as", "Inferred type", "Role", "Non-null", "Missing", "Distinct"], rows[: (25 if inp.concise else 400)], "Column inventory"),
    ] + ([_p(f"Showing the first 25 of {len(rows)} columns; the detailed report lists all of them.")] if inp.concise and len(rows) > 25 else [])


def _types_roles(inp: ReportInput) -> List[Block]:
    cols = inp.profile.get("columns", [])
    roles = _role_counts(cols)
    types: Dict[str, int] = {}
    for c in cols:
        types[c["inferred_type"]] = types.get(c["inferred_type"], 0) + 1
    blocks: List[Block] = [
        _callout("computed", COMPUTED),
        _table(["Semantic role", "Columns"], [[k, v] for k, v in sorted(roles.items())], "Columns per semantic role"),
        _table(["Inferred type", "Columns"], [[k, v] for k, v in sorted(types.items())], "Columns per inferred type"),
    ]
    unsure = [c for c in cols if c.get("role_uncertainty_reason")]
    if unsure:
        blocks += [_h("Roles inferred with lower confidence"), _ul([f"{c['name']} ({c['semantic_role']}): {c['role_uncertainty_reason']}" for c in unsure[:15]])]
    blocks.append(_p("Roles are inferred automatically from values and names (for example, a numeric column with unique integers is treated as an identifier). Roles decide which analyses are offered; please review them for important columns."))
    return blocks


def _descriptive(inp: ReportInput) -> List[Block]:
    cols = inp.profile.get("columns", [])
    num = [c for c in cols if c.get("numeric_summary") and c["semantic_role"] == "measure"]
    blocks: List[Block] = [_callout("computed", COMPUTED)]
    if num:
        rows = [[c["name"], s["count"], s["mean"], s["std"], s["min"], s["q25"], s["median"], s["q75"], s["max"], s["skewness"]] for c in num for s in [c["numeric_summary"]]]
        blocks.append(_table(["Column", "n", "Mean", "Std", "Min", "Q1", "Median", "Q3", "Max", "Skew"], rows[: (12 if inp.concise else 100)], "Numeric columns"))
    else:
        blocks.append(_p("The dataset has no numeric measure columns."))
    cat = [c for c in cols if c.get("categorical_summary") and c["semantic_role"] in ("category", "boolean")]
    if cat and not inp.concise:
        rows = [[c["name"], c["categorical_summary"]["unique_count"], c["categorical_summary"].get("most_frequent_value"), f"{c['categorical_summary'].get('most_frequent_percentage', 0)}%"] for c in cat]
        blocks.append(_table(["Column", "Distinct", "Most frequent", "Share"], rows[:100], "Categorical columns"))
    return blocks


def _missing(inp: ReportInput) -> List[Block]:
    m = inp.profile.get("missingness", {})
    blocks: List[Block] = [
        _callout("computed", COMPUTED),
        _p(f"{m.get('missing_cells', 0):,} of {m.get('total_cells', 0):,} cells are missing ({_f(m.get('overall_missing_percentage', 0))}%). "
           "Missing values are never filled in or deleted in the original data; each analysis states how many rows it excluded."),
    ]
    data = [d for d in m.get("missingness_chart_data", []) if d.get("missing_count", 0) > 0][:15]
    if data:
        spec = chart_builders.bar("missing", "Missing values by column (%)", [d["column"] for d in data], [d["missing_percentage"] for d in data], "% missing", "", horizontal=True).spec
        blocks.append(_img(_png(spec), "Share of missing cells per column"))
        blocks.append(_table(["Column", "Missing", "% missing"], [[d["column"], d["missing_count"], f"{d['missing_percentage']}%"] for d in data], "Columns with missing values"))
    else:
        blocks.append(_p("No missing values were found."))
    pats = m.get("missingness_patterns") or []
    if pats and not inp.concise:
        blocks.append(_h("Missingness patterns"))
        blocks.append(_ul([str(p)[:240] for p in pats[:8]]))
    return blocks


def _duplicates(inp: ReportInput) -> List[Block]:
    d = inp.profile.get("duplicates", {})
    blocks: List[Block] = [_callout("computed", COMPUTED), _kv([
        ("Exact duplicate rows", d.get("exact_duplicate_rows_count", 0)),
        ("Share of rows", f"{_f(d.get('exact_duplicate_percentage', 0))}%"),
        ("Candidate key columns", ", ".join(d.get("candidate_duplicate_keys", [])) or "none detected"),
    ])]
    if d.get("duplicate_rows_sample") and not inp.concise:
        sample = d["duplicate_rows_sample"][:5]
        cols = list(sample[0].keys())[:8]
        blocks.append(_table(cols, [[r.get(c, "") for c in cols] for r in sample], "Examples of duplicated rows (nothing was removed)"))
    blocks.append(_p("Repeated identifiers are not treated as duplicate rows unless every column matches."))
    return blocks


def _quality(inp: ReportInput) -> List[Block]:
    warns = inp.profile.get("quality_warnings", [])
    order = {"high": 0, "medium": 1, "low": 2}
    warns = sorted(warns, key=lambda w: order.get(str(w.get("severity", "low")).lower(), 3))
    if not warns:
        return [_callout("computed", COMPUTED), _p("No data-quality findings were raised.")]
    rows = [[w.get("severity", ""), w.get("column") or "–", w.get("check_type", ""), w.get("message", "")] for w in warns[: (10 if inp.concise else 100)]]
    return [_callout("computed", COMPUTED), _table(["Severity", "Column", "Check", "Finding"], rows, "Findings (nothing was changed or removed)")]


def _univariate(inp: ReportInput) -> List[Block]:
    dist = inp.profile.get("distributions", {})
    limit = 3 if inp.concise else 8
    blocks: List[Block] = [_callout("computed", COMPUTED)]
    cols_by_name = {c["name"]: c for c in inp.profile.get("columns", [])}
    shown = 0
    for h in dist.get("histograms", []):
        if shown >= limit:
            break
        bins = h.get("bins", [])
        if not bins:
            continue
        edges = [bins[0]["bin_start"]] + [b["bin_end"] for b in bins]
        spec = chart_builders.histogram_bars(h["column"], f"Distribution of {h['column']}", edges, [b["count"] for b in bins], h["column"]).spec
        s = (cols_by_name.get(h["column"]) or {}).get("numeric_summary") or {}
        blocks.append(_img(_png(spec), f"{h['column']}: mean {_f(s.get('mean'))}, median {_f(s.get('median'))}, skewness {_f(s.get('skewness'))}"))
        shown += 1
    cat_shown = 0
    for c in inp.profile.get("columns", []):
        cs = c.get("categorical_summary")
        if cat_shown >= (2 if inp.concise else 5) or not cs or c["semantic_role"] not in ("category", "boolean") or not cs.get("top_values"):
            continue
        tv = cs["top_values"][:10]
        spec = chart_builders.bar(c["name"], f"Most frequent values of {c['name']}", [str(t["value"]) for t in tv], [t["count"] for t in tv], c["name"], "Count").spec
        blocks.append(_img(_png(spec), f"{c['name']}: {cs['unique_count']} distinct values"))
        cat_shown += 1
    if shown == 0 and cat_shown == 0:
        blocks.append(_p("No distributions to show."))
    return blocks


def _correlation_pairs(profile: Dict[str, Any]) -> List[tuple]:
    pm = (profile.get("relationships") or {}).get("pearson") or {}
    cols, mat = pm.get("columns", []), pm.get("matrix", {})
    pairs = []
    for i, a in enumerate(cols):
        for b in cols[i + 1:]:
            r = (mat.get(a) or {}).get(b)
            if isinstance(r, (int, float)):
                pairs.append((a, b, float(r)))
    return sorted(pairs, key=lambda t: -abs(t[2]))


def _bivariate(inp: ReportInput) -> List[Block]:
    rel = inp.profile.get("relationships") or {}
    blocks: List[Block] = [_callout("computed", COMPUTED)]
    assoc = rel.get("categorical_associations") or []
    if assoc:
        top = sorted(assoc, key=lambda a: -(a.get("cramers_v") or 0))[: (3 if inp.concise else 8)]
        blocks.append(_table(["Column X", "Column Y", "Cramér's V", "Chi-square", "p-value"], [[a["column_x"], a["column_y"], a["cramers_v"], a["chi2"], a["p_value"]] for a in top], "Strongest associations between categorical columns"))
        blocks.append(_p("Cramér's V ranges from 0 (no association) to 1. p-values here are exploratory; with many pairs tested, some will look significant by chance."))
    refs = [a for a in inp.analyses if a.result.operation in (
        "group_by", "group_comparison", "crosstab", "scatter_plot", "t_test_independent", "t_test_paired", "anova_one_way", "chi_square",
        "mann_whitney", "kruskal_wallis", "wilcoxon_signed_rank", "kmeans", "pca", "linear_regression", "classification")]
    if refs:
        blocks.append(_h("Requested bivariate and multivariate analyses"))
        blocks.append(_ul([f"{a.label}: {a.result.summary_text}" for a in refs]))
    if not assoc and not refs:
        blocks.append(_p("No bivariate results are available. Ask a question or run an analysis in the workspace and regenerate the report."))
    return blocks


def _correlations(inp: ReportInput) -> List[Block]:
    pairs = _correlation_pairs(inp.profile)
    blocks: List[Block] = [_callout("computed", COMPUTED)]
    pm = (inp.profile.get("relationships") or {}).get("pearson") or {}
    cols, mat = pm.get("columns", []), pm.get("matrix", {})
    if len(cols) >= 2:
        z = [[(mat.get(a) or {}).get(b) for b in cols] for a in cols]
        spec = chart_builders.heatmap("corr", "Pearson correlation", z, cols, cols, zmin=-1, zmax=1).spec
        blocks.append(_img(_png(spec), "Pearson correlation matrix of numeric measures"))
        sp = (inp.profile.get("relationships") or {}).get("spearman", {}).get("matrix", {})
        rows = [[a, b, r, (sp.get(a) or {}).get(b)] for a, b, r in pairs[: (5 if inp.concise else 15)]]
        blocks.append(_table(["Column A", "Column B", "Pearson r", "Spearman rho"], rows, "Strongest pairs"))
        blocks.append(_p("Pearson r measures linear association; Spearman rho measures monotonic association and is less sensitive to outliers. A strong correlation does not show that one variable causes the other."))
    else:
        blocks.append(_p("Fewer than two numeric measures are available, so no correlations were computed."))
    return blocks


def _time(inp: ReportInput) -> List[Block]:
    dates = [c for c in inp.profile.get("columns", []) if c.get("date_summary") and c["semantic_role"] == "datetime"]
    time_runs = [a for a in inp.analyses if a.result.operation in ("time_trend", "date_distribution")]
    if not dates and not time_runs:
        return [_p("Not applicable: the dataset has no date/time column.")]
    blocks: List[Block] = [_callout("computed", COMPUTED)]
    if dates:
        rows = [[c["name"], d.get("min_date"), d.get("max_date"), d.get("date_range_days"), d.get("invalid_date_count"), f"{round(d.get('parse_success_rate', 0) * 100, 1) if d.get('parse_success_rate', 0) <= 1 else d.get('parse_success_rate')}%"] for c in dates for d in [c["date_summary"]]]
        blocks.append(_table(["Column", "Earliest", "Latest", "Span (days)", "Unparseable", "Parsed"], rows, "Date/time columns"))
    if time_runs:
        blocks += [_h("Requested time-based analyses"), _ul([f"{a.label}: {a.result.summary_text}" for a in time_runs]), _p("Their charts are in section 14.")]
    else:
        blocks.append(_p("No time-based analysis was run in this session; ask for a trend over time to add one."))
    return blocks


def _scope_line(r: AnalysisResultResponse) -> str:
    kind = "approximate (sample)" if r.is_approximate else "exact (full dataset)"
    return f"{kind}; {r.records_used:,} of {r.records_examined:,} rows used"


def _user_analyses(inp: ReportInput) -> List[Block]:
    if not inp.analyses:
        return [_p("No analyses were requested in this session.")]
    blocks: List[Block] = []
    for i, a in enumerate(inp.analyses, start=1):
        r = a.result
        blocks.append(_h(f"{i}. {a.label}"))
        pairs = [("Operation", r.operation.replace("_", " ")), ("Columns", ", ".join(r.columns_used) or "–"), ("Rows", _scope_line(r))]
        if r.filters_applied and r.filters_applied.conditions:
            pairs.append(("Filters", "see methodology"))
        blocks.append(_kv(pairs))
        blocks.append(_callout("computed", f"Computed result: {r.summary_text}" + (f" {r.interpretation}" if r.interpretation else "")))
        if a.ai_text:
            blocks.append(_callout("ai", f"{AI_LABEL}\n\n{a.ai_text}"))
        if not inp.concise:
            blocks.append(_p(f"Method: {r.methodology}"))
        if r.warnings:
            blocks.append(_callout("warning", "Warnings: " + " ".join(r.warnings[: (3 if inp.concise else 10)])))
    return blocks


def _charts_tables(inp: ReportInput) -> List[Block]:
    if not inp.analyses:
        return [_p("No analysis results to show.")]
    blocks: List[Block] = [_callout("computed", COMPUTED)]
    chart_cap = 2 if inp.concise else 6
    row_cap = 8 if inp.concise else 25
    for i, a in enumerate(inp.analyses, start=1):
        r = a.result
        if not r.charts and not r.tables:
            continue
        blocks.append(_h(f"{i}. {a.label}"))
        for c in r.charts[:chart_cap]:
            blocks.append(_img(_png(c.spec), c.title))
        for t in r.tables[: (1 if inp.concise else 3)]:
            shown = t.rows[:row_cap]
            cols = t.columns[:9]
            note = f"{t.name}: showing {len(shown)} of {t.total_rows:,} rows" + (" (columns truncated)" if len(t.columns) > 9 else "")
            blocks.append(_table(cols, [[row.get(c) if isinstance(row.get(c), str) else _f(row.get(c)) for c in cols] for row in shown], note))
    return blocks


def _limitations(inp: ReportInput) -> List[Block]:
    items = [
        "Every statistic comes from the uploaded file as parsed; rows with missing or unparseable values are excluded per analysis, never imputed or deleted from the original.",
        "Associations and group differences are descriptive. They do not establish causes.",
        "Outliers are flagged, not removed; whether they are errors or real extremes is a decision for the data owner.",
        "Column roles and types are inferred automatically and may need review.",
    ]
    if any(a.result.is_approximate for a in inp.analyses):
        items.append("Some analyses were computed on a seeded random sample and are approximate; they are marked as such.")
    tests = [a for a in inp.analyses if a.result.operation in ("t_test_independent", "t_test_paired", "anova_one_way", "chi_square", "mann_whitney", "kruskal_wallis", "wilcoxon_signed_rank")]
    if len(tests) >= 3:
        items.append(f"{len(tests)} hypothesis tests were run; without a multiple-comparison correction some 'significant' results can arise by chance.")
    if any(a.ai_text for a in inp.analyses):
        items.append("AI-written explanations may be incomplete or wrong. Numbers in them were checked against computed results, but interpretation remains the reader's responsibility.")
    blocks: List[Block] = [_ul(items)]
    seen: List[str] = []
    for a in inp.analyses:
        for w in a.result.warnings:
            if w not in seen:
                seen.append(w)
    if seen:
        blocks += [_h("Warnings raised during the analyses"), _ul(seen[: (6 if inp.concise else 30)])]
    return blocks


def _reproducibility(inp: ReportInput) -> List[Block]:
    versions: Dict[str, str] = {}
    for a in inp.analyses:
        versions.update(a.result.execution.library_versions)
    blocks: List[Block] = [_kv([
        ("Dataset id", inp.dataset_id),
        ("File SHA-256", inp.checksum_sha256),
        ("Dataset fingerprint", inp.fingerprint),
        ("Parse options", ", ".join(f"{k}={v}" for k, v in inp.parse_options.items() if v) or "defaults"),
        ("Library versions", ", ".join(f"{k} {v}" for k, v in versions.items()) or "–"),
        ("Random seeds", ", ".join(sorted({str(a.result.execution.seed) for a in inp.analyses})) or "–"),
    ]), _p("The original file is never modified. To reproduce a result, reload the file with the parse options above and apply the code listed below; the dataset fingerprint changes if the file or parse options change.")]
    if not inp.concise:
        for i, a in enumerate(inp.analyses, start=1):
            code = a.result.execution.code or ""
            if code:
                blocks += [_h(f"Code for analysis {i}: {a.label}"), _code("\n".join(code.splitlines()[:70]))]
    return blocks


