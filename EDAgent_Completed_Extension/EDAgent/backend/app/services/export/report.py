def _register_fonts() -> tuple:
    """DejaVu ships with matplotlib and covers the symbols used in reports (×, ², …)."""
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont

    fonts = os.path.join(os.path.dirname(matplotlib.__file__), "mpl-data", "fonts", "ttf")
    try:
        for name, file in (("DejaVu", "DejaVuSans.ttf"), ("DejaVu-Bold", "DejaVuSans-Bold.ttf"), ("DejaVu-Mono", "DejaVuSansMono.ttf")):
            if name not in pdfmetrics.getRegisteredFontNames():
                pdfmetrics.registerFont(TTFont(name, os.path.join(fonts, file)))
        return "DejaVu", "DejaVu-Bold", "DejaVu-Mono"
    except Exception:  # fall back to the built-in Latin fonts
        return "Helvetica", "Helvetica-Bold", "Courier"


def render_pdf(inp: ReportInput, sections: List[Section]) -> bytes:
    from reportlab.lib import colors
    from reportlab.lib.enums import TA_LEFT
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.lib.units import cm
    from reportlab.platypus import Image, KeepTogether, PageBreak, Paragraph, Preformatted, SimpleDocTemplate, Spacer, Table, TableStyle

    base, bold, mono = _register_fonts()
    st = {
        "title": ParagraphStyle("t", fontName=bold, fontSize=22, leading=26, spaceAfter=4),
        "sub": ParagraphStyle("s", fontName=base, fontSize=9, textColor=colors.HexColor("#64748b"), spaceAfter=14),
        "h2": ParagraphStyle("h2", fontName=bold, fontSize=14, leading=18, spaceBefore=16, spaceAfter=6, textColor=colors.HexColor("#0f172a")),
        "h3": ParagraphStyle("h3", fontName=bold, fontSize=10.5, leading=14, spaceBefore=10, spaceAfter=3),
        "p": ParagraphStyle("p", fontName=base, fontSize=9, leading=13, alignment=TA_LEFT, spaceAfter=5),
        "cell": ParagraphStyle("c", fontName=base, fontSize=7.5, leading=9.5),
        "cellh": ParagraphStyle("ch", fontName=bold, fontSize=7.5, leading=9.5),
        "cap": ParagraphStyle("cap", fontName=base, fontSize=7.5, textColor=colors.HexColor("#64748b"), spaceAfter=6),
        "code": ParagraphStyle("code", fontName=mono, fontSize=6.8, leading=8.4, backColor=colors.HexColor("#f1f5f9"), borderPadding=4, spaceAfter=8),
    }
    kinds = {
        "computed": ("COMPUTED", "#eff6ff", "#2563eb"),
        "ai": ("AI-WRITTEN", "#f5f3ff", "#7c3aed"),
        "warning": ("WARNING", "#fffbeb", "#d97706"),
        "note": ("NOTE", "#f8fafc", "#64748b"),
    }
    width = A4[0] - 3.6 * cm

    def para(text: str, style: str = "p") -> Paragraph:
        return Paragraph(escape(str(text)).replace("\n", "<br/>"), st[style])

    story: List[Any] = [Spacer(1, 1.2 * cm), para(inp.title, "title"),
                        para(f"{inp.dataset_name} · generated {inp.generated_at.strftime('%Y-%m-%d %H:%M UTC')} · {'concise' if inp.concise else 'detailed'} report", "sub")]

    for sec in sections:
        story.append(Paragraph(f"{sec.number}. {escape(sec.title)}", st["h2"]))
        for b in sec.blocks:
            t = b["type"]
            if t == "p":
                story.append(para(b["text"]))
            elif t == "h3":
                story.append(para(b["text"], "h3"))
            elif t == "ul":
                story += [Paragraph("• " + escape(str(i)), ParagraphStyle("li", parent=st["p"], leftIndent=12, firstLineIndent=-8, spaceAfter=2)) for i in b["items"]]
                story.append(Spacer(1, 4))
            elif t in ("kv", "table"):
                if t == "kv":
                    rows = [[Paragraph(escape(str(k)), st["cellh"]), Paragraph(escape(str(v)), st["cell"])] for k, v in b["pairs"]]
                    col_w = [width * 0.27, width * 0.73]
                    tbl = Table(rows, colWidths=col_w)
                    tbl.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#cbd5e1")), ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#f8fafc")), ("VALIGN", (0, 0), (-1, -1), "TOP")]))
                    story += [tbl, Spacer(1, 6)]
                else:
                    cols = b["columns"]
                    rows = [[Paragraph(escape(str(c)), st["cellh"]) for c in cols]] + [[Paragraph(escape(str(c)[:140]), st["cell"]) for c in r] for r in b["rows"]]
                    # Wider first/last text columns get more room; numeric ones stay narrow.
                    longest = [max([len(str(cols[i]))] + [len(str(r[i])) for r in b["rows"][:40]]) for i in range(len(cols))]
                    weights = [min(max(l, 6), 44) for l in longest]
                    total = sum(weights)
                    tbl = Table(rows, colWidths=[width * w / total for w in weights], repeatRows=1)
                    tbl.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#cbd5e1")), ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#f1f5f9")), ("VALIGN", (0, 0), (-1, -1), "TOP"),
                                             ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#fafafa")])]))
                    story.append(para(b["caption"], "cap") if b.get("caption") else Spacer(1, 0))
                    story += [tbl, Spacer(1, 8)]
            elif t == "image":
                img = Image(io.BytesIO(b["png"]))
                ratio = img.imageHeight / float(img.imageWidth)
                w = min(width, 15.5 * cm)
                img.drawWidth, img.drawHeight = w, w * ratio
                story.append(KeepTogether([img, para(b["caption"], "cap")]))
            elif t == "callout":
                label, bg, bar = kinds[b["kind"]]
                cell = Paragraph(f"<font color='{bar}'><b>{label}</b></font>  " + escape(b["text"]).replace("\n", "<br/>"), st["p"])
                box = Table([[cell]], colWidths=[width])
                box.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, -1), colors.HexColor(bg)), ("LINEBEFORE", (0, 0), (0, -1), 2.2, colors.HexColor(bar)), ("LEFTPADDING", (0, 0), (-1, -1), 8), ("TOPPADDING", (0, 0), (-1, -1), 4), ("BOTTOMPADDING", (0, 0), (-1, -1), 2)]))
                story += [box, Spacer(1, 5)]
            elif t == "code":
                story.append(Preformatted(b["text"][:6000], st["code"]))

    def footer(canvas, doc):
        canvas.saveState()
        canvas.setFont(base, 7.5)
        canvas.setFillColor(colors.HexColor("#64748b"))
        canvas.drawString(1.8 * cm, 1.1 * cm, f"EDAgent · {inp.dataset_name}")
        canvas.drawRightString(A4[0] - 1.8 * cm, 1.1 * cm, f"Page {doc.page}")
        canvas.restoreState()

    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=1.8 * cm, rightMargin=1.8 * cm, topMargin=1.6 * cm, bottomMargin=1.8 * cm, title=inp.title, author="EDAgent")
    doc.build(story, onFirstPage=footer, onLaterPages=footer)
    return buf.getvalue()
