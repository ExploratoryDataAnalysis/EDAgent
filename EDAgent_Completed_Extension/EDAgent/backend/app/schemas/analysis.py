"""
Analysis Catalogue & Execution Schemas
Directly maps to Section 5.3, 5.4, 6.1, 8.1 and 8.2 of the project specification.

`StructuredAnalysisPlan` is the *only* thing the AI layer may produce. It is plain data:
operation name + column names + parameters. It never contains code or SQL, and every
column/value in it is validated against the dataset schema before anything runs.
"""

import uuid
from datetime import datetime
from enum import Enum
from typing import Any, Dict, List, Literal, Optional, Union

from pydantic import Field

from app.schemas.common import BaseSchema


class AnalysisOperationEnum(str, Enum):
    # Descriptive / distribution
    DESCRIPTIVE_STATS = "descriptive_stats"
    FREQUENCY = "frequency"
    HISTOGRAM = "histogram"
    BOXPLOT = "boxplot"
    VIOLIN_PLOT = "violin_plot"
    # Outliers
    OUTLIER_IQR = "outlier_iqr"
    OUTLIER_ZSCORE = "outlier_zscore"
    # Relationships & grouping
    CORRELATION = "correlation"
    SCATTER_PLOT = "scatter_plot"
    CROSSTAB = "crosstab"
    GROUP_BY = "group_by"
    GROUP_COMPARISON = "group_comparison"
    FILTER_ROWS = "filter_rows"
    # Time
    TIME_TREND = "time_trend"
    DATE_DISTRIBUTION = "date_distribution"
    CUSTOM_CHART = "custom_chart"
    # Hypothesis tests
    T_TEST_INDEPENDENT = "t_test_independent"
    T_TEST_PAIRED = "t_test_paired"
    ANOVA_ONE_WAY = "anova_one_way"
    CHI_SQUARE = "chi_square"
    MANN_WHITNEY = "mann_whitney"
    KRUSKAL_WALLIS = "kruskal_wallis"
    WILCOXON = "wilcoxon_signed_rank"
    # Advanced exploration / modelling
    KMEANS = "kmeans"
    PCA = "pca"
    LINEAR_REGRESSION = "linear_regression"
    CLASSIFICATION = "classification"


class MissingPolicyEnum(str, Enum):
    EXCLUDE_AND_REPORT = "exclude_and_report"
    FAIL_ON_MISSING = "fail_on_missing"


class ScopeEnum(str, Enum):
    FULL_DATASET = "full_dataset"
    SAMPLE = "sample"


class FilterOperatorEnum(str, Enum):
    EQ = "eq"
    NE = "ne"
    GT = "gt"
    GTE = "gte"
    LT = "lt"
    LTE = "lte"
    IN = "in"
    NOT_IN = "not_in"
    CONTAINS = "contains"
    NOT_CONTAINS = "not_contains"
    STARTS_WITH = "starts_with"
    BETWEEN = "between"
    IS_NULL = "is_null"
    NOT_NULL = "not_null"


class FilterCondition(BaseSchema):
    """One comparison, e.g. {column: "salary", operator: "gt", value: 50000}."""
    column: str
    operator: FilterOperatorEnum
    value: Optional[Any] = None  # scalar, list (in/not_in) or [low, high] (between)


class FilterGroup(BaseSchema):
    """AND/OR group of conditions; groups may nest (validated to a small maximum depth)."""
    logic: Literal["and", "or"] = "and"
    conditions: List[Union[FilterCondition, "FilterGroup"]] = Field(default_factory=list)


FilterGroup.model_rebuild()


class StructuredAnalysisPlan(BaseSchema):
    """Machine-validated structured plan generated by the AI or by the workspace UI."""
    operation: AnalysisOperationEnum
    column: Optional[str] = None                    # primary variable
    target_columns: List[str] = Field(default_factory=list)  # multi-column operations
    group_by: List[str] = Field(default_factory=list)
    date_column: Optional[str] = None               # time-based operations
    aggregation: str = "mean"                       # sum|mean|median|count|min|max|std|nunique
    filters: Optional[FilterGroup] = None
    sort_by: Optional[str] = None
    sort_order: Literal["asc", "desc"] = "desc"
    top_n: Optional[int] = Field(default=None, ge=1, le=1000)
    bins: Optional[int] = Field(default=None, ge=2, le=200)  # None = automatic (Freedman-Diaconis)
    interval: Literal["day", "week", "month", "quarter", "year"] = "month"
    method: Optional[str] = None                    # pearson|spearman, test variants, ...
    missing_policy: MissingPolicyEnum = MissingPolicyEnum.EXCLUDE_AND_REPORT
    scope: ScopeEnum = ScopeEnum.FULL_DATASET
    sample_size: Optional[int] = Field(default=None, ge=100, le=1_000_000)
    seed: int = 42                                   # every stochastic step is reproducible
    chart_type: Optional[str] = None
    parameters: Dict[str, Any] = Field(default_factory=dict)  # operation specific, whitelisted per tool


class ResultTable(BaseSchema):
    name: str
    columns: List[str]
    rows: List[Dict[str, Any]]
    total_rows: int
    truncated: bool = False


class ResultChart(BaseSchema):
    id: str
    title: str
    kind: str  # bar, histogram, box, scatter, heatmap, line, violin, pie
    spec: Dict[str, Any]  # Plotly figure JSON ({"data": [...], "layout": {...}})


class ExclusionNote(BaseSchema):
    reason: str
    count: int
    column: Optional[str] = None


class ExecutionInfo(BaseSchema):
    time_ms: float
    engine: str = "pandas"
    seed: int = 42
    cache_hit: bool = False
    code: str = ""  # reproducible snippet
    library_versions: Dict[str, str] = Field(default_factory=dict)
    executed_at: str = ""


class AnalysisResultResponse(BaseSchema):
    """Reusable result object: numbers, tables, charts, methodology and warnings together."""
    id: uuid.UUID = Field(default_factory=uuid.uuid4)
    request_id: Optional[uuid.UUID] = None
    dataset_id: uuid.UUID
    dataset_fingerprint: str = ""
    operation: str
    columns_used: List[str] = Field(default_factory=list)
    plan: StructuredAnalysisPlan
    filters_applied: Optional[FilterGroup] = None
    # Observation accounting (spec 10: always show included/excluded rows)
    records_examined: int
    records_used: int
    records_excluded: int = 0
    exclusions: List[ExclusionNote] = Field(default_factory=list)
    missing_value_handling: str = ""
    # Exact vs sampled
    is_sampled: bool = False
    sample_size: Optional[int] = None
    sampling_method: Optional[str] = None
    is_approximate: bool = False
    # Content
    metrics: Dict[str, Any] = Field(default_factory=dict)
    tables: List[ResultTable] = Field(default_factory=list)
    charts: List[ResultChart] = Field(default_factory=list)
    warnings: List[str] = Field(default_factory=list)
    methodology: str = ""
    summary_text: str = ""  # deterministic summary built from the computed numbers
    interpretation: Optional[str] = None  # hypothesis tests / modelling notes (also computed)
    execution: ExecutionInfo
    created_at: Optional[datetime] = None


class AnalysisExecuteRequest(BaseSchema):
    """Direct (non-chat) execution of an explicit plan from the workspace UI."""
    session_id: uuid.UUID
    plan: StructuredAnalysisPlan
    label: Optional[str] = Field(default=None, max_length=300)


class AnalysisRequestResponse(BaseSchema):
    id: uuid.UUID
    session_id: uuid.UUID
    user_query: str
    structured_plan: Optional[StructuredAnalysisPlan] = None
    status: str
    error_message: Optional[str] = None
